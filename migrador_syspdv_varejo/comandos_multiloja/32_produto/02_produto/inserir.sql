-- Produto NOVO na loja adicional: MANTEM o codigo do SysPDV se estiver livre no VarejoFacil (inclusive o codigo que
-- e o proprio EAN, > 999999); senao o proximo livre (< 999999). Secao/grupo/subgrupo traduzidos pelo vinculo,
-- vinculo novo = TRUE.
WITH novo AS (
INSERT INTO produto (prodid, procod, procodint, prodesrdz, prodes, seccod, trbid, prounid, propesvar, procomtip, procomcap, procompro, procomven, provld, profrtloj, proestmin, proestmax, proqtdetq, pronumser, proflgalt, protaba, probontip, probonfat, proctrest, proesp, procomp, proctrvld, proenvbal, prodatcadinc, prodatcadalt, funcod, prodesvar, proend, grpcod, sgpcod, proiteemb, procstmed, proqtdmaxvda, propesbrt, propesliq, proforlin, prodatforlin, proundcmp, loccod, proundref, promedref, protipipi, provlragr, protipagr, proprcvar, proiat, proippt, proncm, profin, pro_modelo, mar_codigo, proipi, proinczf, properpda, proncmexc, proiteembvda, procodanp, gencodigo, natcodigo, pro_compoe_total_nota_fiscal, procest, prod_bloqueado_compra, pro_permite_desconto, procodorigem, proiteembtrs, prod_dias_seguranca)
VALUES (nextval('sq_produto'), (CASE WHEN NOT EXISTS (SELECT 1 FROM produto WHERE procod = %(procod)s::bigint) THEN %(procod)s::bigint ELSE (SELECT COALESCE(MAX(procod), 0) + 1 FROM produto WHERE procod < 999999) END), %(procodint)s,
        %(prodesrdz)s,
        %(prodes)s,
        COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'secao' AND codigo_origem = %(seccod)s::int::text), %(seccod)s::int),
        %(trbid)s,
        %(prounid)s,
        %(propesvar)s,
        %(procomtip)s,
        %(procomcap)s,
        %(procompro)s,
        %(procomven)s,
        %(provld)s,
        %(profrtloj)s,
        %(proestmin)s,
        %(proestmax)s,
        %(proqtdetq)s,
        %(pronumser)s,
        %(proflgalt)s,
        %(protaba)s,
        %(probontip)s,
        %(probonfat)s,
        %(proctrest)s,
        %(proesp)s,
        %(procomp)s,
        %(proctrvld)s,
        %(proenvbal)s,
        %(prodatcadinc)s,
        %(prodatcadalt)s,
        %(funcod)s,
        %(prodesvar)s,
        %(proend)s,
        (SELECT g.grpcod FROM grupo_produto g WHERE g.seccod = COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'secao' AND codigo_origem = %(seccod)s::int::text), %(seccod)s::int) AND g.grpcod = COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'grupo' AND codigo_origem = %(seccod)s::int::text || '|' || %(grpcod)s::int::text), %(grpcod)s::int) LIMIT 1),
        (SELECT s.sgpcod FROM subgrupo_produto s WHERE s.seccod = COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'secao' AND codigo_origem = %(seccod)s::int::text), %(seccod)s::int) AND s.grpcod = COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'grupo' AND codigo_origem = %(seccod)s::int::text || '|' || %(grpcod)s::int::text), %(grpcod)s::int) AND s.sgpcod = COALESCE((SELECT codigo_vf FROM migracao_multiloja.vinculo WHERE loj_codigo = {{loja_destino}} AND tipo = 'subgrupo' AND codigo_origem = %(seccod)s::int::text || '|' || %(grpcod)s::int::text || '|' || %(sgpcod)s::int::text), %(sgpcod)s::int) LIMIT 1),
        %(proiteemb)s,
        %(procstmed)s,
        %(proqtdmaxvda)s,
        %(propesbrt)s,
        %(propesliq)s,
        %(proforlin)s,
        %(prodatforlin)s,
        %(proundcmp)s,
        %(loccod)s,
        %(proundref)s,
        %(promedref)s,
        %(protipipi)s,
        %(provlragr)s,
        %(protipagr)s,
        %(proprcvar)s,
        %(proiat)s,
        %(proippt)s,
        %(proncm)s,
        %(profin)s,
        %(pro_modelo)s,
        %(mar_codigo)s,
        %(proipi)s,
        %(proinczf)s,
        %(properpda)s,
        %(proncmexc)s,
        %(proiteembvda)s,
        %(procodanp)s,
        %(gencodigo)s,
        %(natcodigo)s,
        %(pro_compoe_total_nota_fiscal)s,
        %(procest)s,
        %(prod_bloqueado_compra)s,
        %(pro_permite_desconto)s,
        %(procodorigem)s,
        %(proiteembtrs)s,
        %(prod_dias_seguranca)s)
    RETURNING procod
)
INSERT INTO migracao_multiloja.vinculo (loj_codigo, tipo, codigo_origem, codigo_vf, novo)
SELECT {{loja_destino}}, 'produto', %(procod)s::bigint::text, procod, TRUE FROM novo
