-- Versao para SQL Server (TRIM so existe a partir do SQL Server 2017; LTRIM(RTRIM()) funciona em todos).
-- Filtro "(... OR :opcao_fora_de_linha = 1)": opcao "Incluir produtos fora de linha" do Produto.

-- Pentaho: SF - CLASSIFICACAO TRIBUTARIA (Produto_Produto) (T-cenario_fiscal_produto_produto)
SELECT t2.ID_NUM, t1.PROCOD, t1.SECCOD, t3.SECDES, t1.GRPCOD, t4.GRPDES, t1.SGRCOD, t5.SGRDES
  FROM PRODUTO t1
  JOIN CLASSIFICACAO_TRIBUTARIA t2 ON t1.CLATRBCODNFCE = t2.CLATRBCOD
  LEFT JOIN SECAO t3 ON t1.SECCOD = t3.SECCOD
  LEFT JOIN GRUPO t4 ON t1.SECCOD = t4.SECCOD AND t1.GRPCOD = t4.GRPCOD
  LEFT JOIN SUBGRUPO t5 ON t1.SECCOD = t5.SECCOD AND t1.GRPCOD = t5.GRPCOD AND t1.SGRCOD = t5.SGRCOD
  JOIN NCM t6 ON t1.PRONCM = t6.NCMCOD
 WHERE COALESCE(LTRIM(RTRIM(t1.CLATRBCODNFCE)), '') <> COALESCE(LTRIM(RTRIM(t6.CLATRBCODNFCE)), '')
   AND t1.PRODES IS NOT NULL
   AND t1.PROCOD <> '00000000000000'
   AND (COALESCE(t1.PROFORLIN, 'N') = 'N' OR :opcao_fora_de_linha = 1)
 ORDER BY t1.PROCOD
