-- Pentaho: FB - PRODUTO (T-Produto_inicial). No Pentaho o filtro proforlin = 'N' esta COMENTADO
-- (migra tudo). Aqui depende da opcao "Incluir produtos fora de linha" da tela:
--   marcada (padrao) = todos os produtos; desmarcada = so PROFORLIN = 'N' (vazio conta como 'N').
-- Os SQLs "FB - Ajuste Secao / Unidade" e "FB - Ajustes campos estourados" faziam UPDATE no
-- SysPDV; aqui viraram CASE na leitura (mesmo resultado, sem alterar o banco do cliente).
SELECT p.PROCOD, p.PROCODINT, p.PRODES, p.PRODESRDZ
     , CASE WHEN p.SECCOD IS NULL OR p.SECCOD IN (SELECT s.SECCOD FROM SECAO s) THEN p.SECCOD
            ELSE (SELECT MAX(s.SECCOD) FROM SECAO s) END AS SECCOD
     , p.TRBID
     , CASE WHEN p.PROUNID IS NULL OR p.PROUNID IN (SELECT u.UNDCOD FROM UNIDADE u) THEN p.PROUNID ELSE 'UN' END AS PROUNID
     , CASE WHEN p.PROUNDCMP IS NULL OR p.PROUNDCMP IN (SELECT u.UNDCOD FROM UNIDADE u) THEN p.PROUNDCMP ELSE 'UN' END AS PROUNDCMP
     , CASE WHEN p.PROUNDFUN IS NULL OR p.PROUNDFUN IN (SELECT u.UNDCOD FROM UNIDADE u) THEN p.PROUNDFUN ELSE 'UN' END AS PROUNDFUN
     , p.PROPESVAR, p.PROCOMTIP, p.PROCOMCAP, p.PROCOMPRO, p.PROCOMVEN, p.PROVLD, p.PROFRTLOJ
     , CASE WHEN p.PROESTMIN > 100000 THEN 0 ELSE p.PROESTMIN END AS PROESTMIN
     , CASE WHEN p.PROESTMAX > 100000 THEN 0 ELSE p.PROESTMAX END AS PROESTMAX
     , p.PROQTDETQ, p.PRONUMSER, p.PROFLGALT, p.PROTABA, p.PROBONTIP, p.PROBONFAT, p.PROCTREST
     , p.PROESP, p.PROCOMP, p.PROCTRVLD, p.PROENVBAL, p.PRODATCADINC, p.PRODESVAR, p.PROEND
     , p.GRPCOD, p.SGRCOD
     , CASE WHEN p.PROITEEMB >= 789000000000 THEN 1 ELSE p.PROITEEMB END AS PROITEEMB
     , CASE WHEN p.PROCSTMED >= 7890000000000 THEN 0 ELSE p.PROCSTMED END AS PROCSTMED
     , CASE WHEN p.PROQTDMAXVDA >= 7890000000000 THEN 0 ELSE p.PROQTDMAXVDA END AS PROQTDMAXVDA
     , CASE WHEN p.PROPESBRT > 100000 THEN 0 ELSE p.PROPESBRT END AS PROPESBRT
     , CASE WHEN p.PROPESLIQ > 100000 THEN 0 ELSE p.PROPESLIQ END AS PROPESLIQ
     , p.PROFORLIN, p.PRODATFORLIN, p.LOCCOD, p.PROMEDFUN, p.PROTIPIPI, p.PROVLRAGR, p.PROTIPAGR
     , p.PROPRCVAR, p.PROIAT, p.PROIPPT, p.PRONCM, p.PROFIN, p.PRO_MODELO, p.PRO_MAR_CODIGO, p.PROIPI
     , p.PROINCZF, p.PROPERPDA, p.PRONCMEXC
     , CASE WHEN p.PROITEEMBVDA >= 789000000000 THEN 1 ELSE p.PROITEEMBVDA END AS PROITEEMBVDA
     , p.PROCODANP, p.NATCODIGO, p.PROCEST, p.PROPERDCN, p.PROCODORIGEM
  FROM PRODUTO p
 WHERE p.PRODES IS NOT NULL
   AND p.PROCOD <> '00000000000000'
   AND (COALESCE(p.PROFORLIN, 'N') = 'N' OR :opcao_fora_de_linha = 1)
 ORDER BY 1
