-- Filtro "(... OR :opcao_fora_de_linha = 1)": opcao "Incluir produtos fora de linha" do Produto.
-- Pentaho: FB - PRODUTO (T-ProdutoPreco_inicial). Os valores "estourados" que o SQL
-- "FB - Ajustes campos estourados" zerava no SysPDV sao zerados aqui na leitura.
SELECT (SELECT r.PRPCOD FROM PROPRIO r) AS PRPCOD
     , p.PROCOD
     , CASE WHEN p.PRODCNMAX >= 7890000000000 THEN 0 ELSE p.PRODCNMAX END AS PRODCNMAX
     , CASE WHEN p.PROPRCVDAVAR >= 7890000000000 THEN 0 ELSE p.PROPRCVDAVAR END AS PROPRCVDAVAR
     , CASE WHEN p.PROPRCOFEVAR >= 7890000000000 THEN 0 ELSE p.PROPRCOFEVAR END AS PROPRCOFEVAR
     , p.PROPRCDATALT
     , CASE WHEN p.PROPRCCST >= 7890000000000 THEN 0 ELSE p.PROPRCCST END AS PROPRCCST
     , CASE WHEN p.PROPRCVDA2 >= 7890000000000 THEN 0 ELSE p.PROPRCVDA2 END AS PROPRCVDA2
     , CASE WHEN p.PROPRCOFE2 >= 7890000000000 THEN 0 ELSE p.PROPRCOFE2 END AS PROPRCOFE2
     , CASE WHEN p.PROPRCVDA3 >= 7890000000000 THEN 0 ELSE p.PROPRCVDA3 END AS PROPRCVDA3
     , CASE WHEN p.PROPRCOFE3 >= 7890000000000 THEN 0 ELSE p.PROPRCOFE3 END AS PROPRCOFE3
     , CASE WHEN p.PROPRC1 >= 7890000000000 THEN 0 ELSE p.PROPRC1 END AS PROPRC1
     , CASE WHEN p.PROPRC2 >= 7890000000000 THEN 0 ELSE p.PROPRC2 END AS PROPRC2
     , CASE WHEN p.PROPRC3 >= 7890000000000 THEN 0 ELSE p.PROPRC3 END AS PROPRC3
     , p.PROPERDCN
     , CASE WHEN p.PROMRG1 >= 7890000000000 THEN 0 ELSE p.PROMRG1 END AS PROMRG1
     , CASE WHEN p.PROMRG2 >= 7890000000000 THEN 0 ELSE p.PROMRG2 END AS PROMRG2
     , CASE WHEN p.PROMRG3 >= 7890000000000 THEN 0 ELSE p.PROMRG3 END AS PROMRG3
     , CASE WHEN p.PROQTDMINPRC2 >= 7890000000000 THEN 0 ELSE p.PROQTDMINPRC2 END AS PROQTDMINPRC2
     , CASE WHEN p.PROQTDMINPRC3 >= 7890000000000 THEN 0 ELSE p.PROQTDMINPRC3 END AS PROQTDMINPRC3
     , CASE WHEN p.PROPRCCSTMED >= 7890000000000 THEN 0 ELSE p.PROPRCCSTMED END AS PROPRCCSTMED
     , CASE WHEN p.PROPRCCSTFIS >= 7890000000000 THEN 0 ELSE p.PROPRCCSTFIS END AS PROPRCCSTFIS
  FROM PRODUTO p
 WHERE p.PRODES IS NOT NULL
   AND p.PROCOD <> '00000000000000'
   AND (COALESCE(p.PROFORLIN, 'N') = 'N' OR :opcao_fora_de_linha = 1)
 ORDER BY 2
