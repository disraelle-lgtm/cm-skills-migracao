-- Versao SQL Server: emissao vazia = vencimento - 30 dias com DATEADD
SELECT ct.CTPID, ct.CTPOBS, ct.CTPNUM, COALESCE(ct.CTPDATEMI, DATEADD(day, -30, ct.CTPDATVNC)) AS CTPDATEMI, ct.CTPVLRNOM, ct.CTPDATVNC, ct.FORCOD,
       p.PRPCOD, f.FORCGC
  FROM CONTAPAGAR ct
 INNER JOIN FORNECEDOR f ON ct.FORCOD = f.FORCOD
 CROSS JOIN PROPRIO p
 WHERE ct.CTPDATPGT IS NULL
   AND ct.CTPTIPPAG = 'A'
   AND f.FORCGC IS NOT NULL
   AND ct.CTPLOGEXCLUSAO = 'N'
 ORDER BY f.FORCGC
