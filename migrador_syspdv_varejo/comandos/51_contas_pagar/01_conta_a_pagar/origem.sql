-- Pentaho: FB - CONTAPAGAR (T-ContaPagar_inicial): contas em aberto, nao excluidas
SELECT ct.CTPID, ct.CTPOBS, ct.CTPNUM, COALESCE(ct.CTPDATEMI, ct.CTPDATVNC - 30) AS CTPDATEMI, ct.CTPVLRNOM, ct.CTPDATVNC, ct.FORCOD,
       p.PRPCOD, f.FORCGC
  FROM CONTAPAGAR ct
 INNER JOIN FORNECEDOR f ON ct.FORCOD = f.FORCOD
 CROSS JOIN PROPRIO p
 WHERE ct.CTPDATPGT IS NULL
   AND ct.CTPTIPPAG = 'A'
   AND f.FORCGC IS NOT NULL
   AND ct.CTPLOGEXCLUSAO = 'N'
 ORDER BY f.FORCGC
