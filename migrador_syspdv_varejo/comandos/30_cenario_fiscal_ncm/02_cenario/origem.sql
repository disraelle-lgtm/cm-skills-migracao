-- Pentaho: SF - CLASSIFICACAO TRIBUTARIA (T-Reforma_Tributaria_inicial): um cenario por
-- classificacao usada na tabela NCM do SysPDV
SELECT t1.CLATRBCODNFCE, t2.ID_NUM, t2.CSTCOD, t2.CLATRBAPL, t2.FUNCODATU
  FROM NCM t1
  LEFT JOIN CLASSIFICACAO_TRIBUTARIA t2 ON t1.CLATRBCODNFCE = t2.CLATRBCOD
 WHERE t1.CLATRBCODNFCE IS NOT NULL
 GROUP BY t1.CLATRBCODNFCE, t2.ID_NUM, t2.CSTCOD, t2.CLATRBAPL, t2.FUNCODATU
