-- BACKUP SQL SERVER

DECLARE @cmdSQL NVARCHAR(200);
SET @cmdSQL = 'BACKUP DATABASE syspdv TO DISK = '
+ CHAR(39)
+'D:\CMSERVICOS\Syspdv-'
+ DateName(WEEKDAY, GETDATE())
+'-full.BAK'
+ CHAR(39)
+ ' WITH init'
+', COMPRESSION';
EXEC MASTER..SP_EXECUTESQL @cmdSQL
GO

DECLARE @chkdsk NVARCHAR (200);
SET @chkdsk = 'RESTORE VERIFYONLY FROM DISK = '
+ CHAR(39)
+ 'D:\CMSERVICOS\Syspdv-'
+ DateName(WEEKDAY, GETDATE())
+'-full.BAK'
+ CHAR(39)
EXEC MASTER..SP_EXECUTESQL @chkdsk
GO