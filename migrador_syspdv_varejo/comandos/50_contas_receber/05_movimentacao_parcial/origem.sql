-- Pentaho: FB - CONTASRECEBERLIQUIDACAO (T-MovimentacaoTituloReceber_Parcial_inicial)
SELECT crl.CRLVLRMUL, crl.CRLVLRJUR, crl.CRLVLRDCN, crl.CRLVLRREC, crl.CRLDAT, crl.CTRID, crl.CRLCTCCOD
  FROM CONTASRECEBERLIQUIDACAO crl
 INNER JOIN CONTARECEBER cr ON crl.CTRID = cr.CTRID
 WHERE cr.CTRTIPPAG = 'P'
 ORDER BY crl.CTRID, crl.CRLDAT
