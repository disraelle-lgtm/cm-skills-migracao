CREATE OR REPLACE FUNCTION HABILITA_OU_DESABILITA_CONSTRANTS(HABILITA_TRIGER BOOLEAN) RETURNS VOID AS
$BODY$
DECLARE
  NOME_TABELA VARCHAR;
BEGIN
  FOR NOME_TABELA IN
  SELECT C.RELNAME
    FROM PG_CLASS AS C
   INNER JOIN PG_ATTRIBUTE AS A ON (A.ATTRELID = C.OID)
   WHERE (UPPER(A.ATTNAME) IN (UPPER('PROCOD'), UPPER('CODIGO_PRODUTO'), UPPER('ID_PRODUTO'), UPPER('RES_CODIGO_PRODUTO'))
      OR  UPPER(A.ATTNAME) LIKE UPPER('%_PROCOD'))
     AND UPPER(C.RELKIND) = 'R'
     AND UPPER(C.RELNAME) NOT IN ('PG_PROC', 'PG_OPERATOR', 'PG_AMPROC', 'PG_CONVERSION', 'PG_SECLABEL',
                                  'PG_SHSECLABEL', 'SQL_LANGUAGES', 'SQL_SIZING_PROFILES', 'ESTATISTICA_PRODUTO_MOVIMENTACAO',
                                  'ESTATISTICA_PRODUTO_VENDA', 'ESTATISTICA_PRODUTO_COMPRA')
   ORDER BY C.RELNAME
   
  LOOP
    IF HABILITA_TRIGER THEN
      RAISE NOTICE 'HABILITANDO TRIGGERS DA TABELA %', NOME_TABELA;
      EXECUTE 'ALTER TABLE ' || NOME_TABELA || ' ENABLE TRIGGER ALL ' ;
    ELSE
      RAISE NOTICE 'DESABILITANDO TRIGGERS DA TABELA %', NOME_TABELA;
      EXECUTE 'ALTER TABLE ' || NOME_TABELA || ' DISABLE TRIGGER ALL ' ;
    END IF;
  END LOOP;

END
$BODY$
LANGUAGE 'plpgsql' ;

DROP FUNCTION APAGAR_PRODUTOS_SEM_MOVIMENTACOES (A_DATA_INICIAL DATE, A_DATA_FINAL DATE, A_CODIGOS_PRODUTOS BIGINT[], A_HABILITA_OU_DESABILITA_CONSTRANTS BOOLEAN) ;

CREATE OR REPLACE FUNCTION APAGAR_PRODUTOS_SEM_MOVIMENTACOES (A_DATA_INICIAL DATE, A_DATA_FINAL DATE, A_CODIGOS_PRODUTOS BIGINT[], A_HABILITA_OU_DESABILITA_CONSTRANTS BOOLEAN) RETURNS BIGINT AS $$
  DECLARE
    NOME_TABELA VARCHAR;
    NOME_COLUNA VARCHAR;
    QUANTIDADE_ANTES BIGINT;
    QUANTIDADE_DEPOIS BIGINT;

  BEGIN

    SELECT COUNT(PROCOD) INTO QUANTIDADE_ANTES FROM PRODUTO ;

    DROP TABLE IF EXISTS PRODUTOS_PARA_EXCLUIR ;

    CREATE TABLE PRODUTOS_PARA_EXCLUIR AS
      WITH CTE_PRODUTOS AS (
           SELECT P.PROCOD 
             FROM PRODUTO P
            WHERE P.PROCOD NOT IN (SELECT EM.PROCOD 
                                     FROM ESTOQUE_MOVIMENTACAO EM
                                    WHERE EM.MOV_TIPO != 'MOVIMENTACAO_INICIAL'
                                      AND EM.MOV_DATA BETWEEN COALESCE(A_DATA_INICIAL, '1990-01-01') AND COALESCE(A_DATA_FINAL, CURRENT_DATE)
                                    GROUP BY EM.PROCOD)
         ) , CTE_ITEM_VENDA AS (
           SELECT IV.PROCOD FROM ITEM_VENDA IV GROUP BY IV.PROCOD
         ) , CTE_ITEM_NOTA_FISCAL AS (
           SELECT INF.PROCOD FROM ITEM_NOTA_FISCAL INF GROUP BY INF.PROCOD
         ) , CTE_ITEM_PEDIDO_COMPRA AS (
           SELECT IPC.PROCOD FROM ITEM_PEDIDO_COMPRA IPC GROUP BY IPC.PROCOD
         )
    SELECT P.PROCOD
      FROM PRODUTO P
     INNER JOIN CTE_PRODUTOS CP ON (CP.PROCOD = P.PROCOD)
      LEFT JOIN CTE_ITEM_VENDA IV ON (IV.PROCOD = P.PROCOD)
      LEFT JOIN CTE_ITEM_NOTA_FISCAL INF ON (INF.PROCOD = P.PROCOD)
      LEFT JOIN CTE_ITEM_PEDIDO_COMPRA IPC ON (IPC.PROCOD = P.PROCOD)
     WHERE 1 = 1
       AND (CASE WHEN A_CODIGOS_PRODUTOS IS NULL THEN P.PROCOD = P.PROCOD ELSE P.PROCOD = ANY(ARRAY[A_CODIGOS_PRODUTOS]) END)
       AND IV.PROCOD IS NULL
       AND INF.PROCOD IS NULL
       AND IPC.PROCOD IS NULL
    ;

    RAISE NOTICE 'DELETANDO REGISTRO DA TABELA ESTATISTICA_PRODUTO_COMPRA';
    DELETE FROM ESTATISTICA_PRODUTO_COMPRA WHERE EPC_DATA_HORA_COMPRA IS NULL AND EPC_PROCOD IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) ;

    RAISE NOTICE 'DELETANDO REGISTRO DA TABELA ESTATISTICA_PRODUTO_VENDA';
    DELETE FROM ESTATISTICA_PRODUTO_VENDA WHERE EPV_DATA_HORA_VENDA IS NULL AND EPV_PROCOD IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) ;

    DROP TABLE IF EXISTS PRODUTOS_PARA_EXCLUIR_2 ;

    CREATE TABLE PRODUTOS_PARA_EXCLUIR_2 AS
    SELECT P.PROCOD
      FROM PRODUTO P
     WHERE P.PROCOD IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR)
       AND P.PROCOD NOT IN (SELECT EPC_PROCOD FROM ESTATISTICA_PRODUTO_COMPRA WHERE EPC_PROCOD IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) GROUP BY EPC_PROCOD)
       AND P.PROCOD NOT IN (SELECT EPV_PROCOD FROM ESTATISTICA_PRODUTO_VENDA  WHERE EPV_PROCOD IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) GROUP BY EPV_PROCOD)
       AND P.PROCOD NOT IN (SELECT PROCOD     FROM ITEM_TRANSFERENCIA         WHERE PROCOD     IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) GROUP BY PROCOD)
       AND P.PROCOD NOT IN (SELECT PROCOD     FROM ITEM_AJUSTE_ESTOQUE        WHERE PROCOD     IN (SELECT PROCOD FROM PRODUTOS_PARA_EXCLUIR) GROUP BY PROCOD)
    ;

    DROP TABLE PRODUTOS_PARA_EXCLUIR ;

    IF (A_HABILITA_OU_DESABILITA_CONSTRANTS = TRUE) THEN
      -- Desabilita as contrants das tabelas que tem alguma relação com produto
      PERFORM HABILITA_OU_DESABILITA_CONSTRANTS(FALSE) ;
    END IF;

    RAISE NOTICE '%, LIMPANDO REFERENCIA DA TABELA ITEM_INVENTARIO', timeofday()::TIMESTAMP;
    UPDATE ITEM_INVENTARIO SET MOV_ID = NULL WHERE PROCOD IN (SELECT CAST(PROCOD AS BIGINT) FROM PRODUTOS_PARA_EXCLUIR_2) ;

    FOR NOME_TABELA, NOME_COLUNA IN
    SELECT C.RELNAME, A.ATTNAME
      FROM PG_CLASS AS C
     INNER JOIN PG_ATTRIBUTE AS A ON (A.ATTRELID = C.OID)
     WHERE (UPPER(A.ATTNAME) IN (UPPER('PROCOD'), UPPER('CODIGO_PRODUTO'), UPPER('ID_PRODUTO'), UPPER('RES_CODIGO_PRODUTO'))
        OR  UPPER(A.ATTNAME) LIKE UPPER('%_PROCOD'))
       AND UPPER(C.RELKIND) = 'R'
       AND UPPER(C.RELNAME) NOT IN ('PG_PROC', 'PG_OPERATOR', 'PG_AMPROC', 'PG_CONVERSION', 'PG_SECLABEL', 'PG_SHSECLABEL', 'SQL_LANGUAGES', 'SQL_SIZING_PROFILES',
                                    'PRODUTOS_PARA_EXCLUIR_2', 'ESTATISTICA_PRODUTO_COMPRA', 'ESTATISTICA_PRODUTO_VENDA', 'ITEM_TRANSFERENCIA', 'ITEM_AJUSTE_ESTOQUE')
     ORDER BY C.RELNAME

    LOOP
      RAISE NOTICE '%, DELETANDO REGISTRO DA TABELA %', timeofday()::TIMESTAMP, NOME_TABELA;
      EXECUTE 'DELETE FROM ' || NOME_TABELA || ' WHERE CAST(' || NOME_COLUNA || ' AS BIGINT) IN (SELECT CAST(PROCOD AS BIGINT) FROM PRODUTOS_PARA_EXCLUIR_2) ' ;
    END LOOP;

    IF (A_HABILITA_OU_DESABILITA_CONSTRANTS = TRUE) THEN
      -- Habilita novamente todas as constrants das tabelas
      PERFORM HABILITA_OU_DESABILITA_CONSTRANTS(TRUE) ;
    END IF;

    RAISE NOTICE 'INSERINDO REGISTROS NA TABELA FILA_SINCRONIZACAO_PANAMA';
    INSERT INTO FILA_SINCRONIZACAO_PANAMA (ID, ORIGEM, IDENTIFICADOR, PRIORIDADE, ENTIDADE_ID, OPERACAO, OBJETO_ID)
    SELECT NEXTVAL('SQ_FILA_SINCRONIZACAO_PANAMA'), 'SCRIPT', 'PRODUTO', 0, PROCOD, 'EXCLUSAO', PROCOD
      FROM PRODUTOS_PARA_EXCLUIR_2
    ;

    DROP TABLE PRODUTOS_PARA_EXCLUIR_2 ;

    SELECT COUNT(PROCOD) INTO QUANTIDADE_DEPOIS FROM PRODUTO ;

    RETURN QUANTIDADE_ANTES - QUANTIDADE_DEPOIS;
  END;

$$ LANGUAGE PLPGSQL;







